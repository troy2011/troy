function createButton(className, text) {
    const button = document.createElement('button');
    button.type = 'button';
    button.className = className;
    button.textContent = text;
    return button;
}

function renderTopics() {
    const list = $('tarotTopicList');
    if (!list) return;
    list.textContent = '';
    TOPICS.forEach((topic) => {
        const button = createButton('', topic.label);
        button.dataset.topicId = topic.id;
        button.setAttribute('role', 'option');
        button.setAttribute('aria-selected', topic.id === state.topicId ? 'true' : 'false');
        button.classList.toggle('is-active', topic.id === state.topicId);
        const sub = document.createElement('small');
        sub.textContent = topic.short;
        button.append(sub);
        button.addEventListener('click', () => {
            state.topicId = topic.id;
            state.resultEdited = false;
            renderTopics();
            updateResult();
        });
        list.append(button);
    });
}

