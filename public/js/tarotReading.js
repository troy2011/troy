function formatReadingBody(text) {
    const value = String(text || '').trim();
    if (!value) return value;
    const lines = value.split(/\n+/)
        .flatMap((section) => section
            .match(/[^。！？!?]+[。！？!?]?/g)
            ?.map((line) => line.trim())
            .filter(Boolean) || [section.trim()])
        .filter(Boolean);
    return lines.join('\n');
}

function getSpecialReadingBody(topicId, card, orientationId) {
    if (topicId === 'love') {
        if (card?.kind === 'major') {
            return LOVE_MAJOR_READINGS[card.number]?.[orientationId] || '';
        }
        if (card?.kind === 'minor') {
            return LOVE_MINOR_READINGS[card.suitId]?.[card.rankId]?.[orientationId] || '';
        }
    }
    if (topicId === 'work') {
        if (card?.kind === 'major') {
            return WORK_MAJOR_READINGS[card.number]?.[orientationId] || '';
        }
        if (card?.kind === 'minor') {
            return WORK_MINOR_READINGS[card.suitId]?.[card.rankId]?.[orientationId] || '';
        }
    }
    if (topicId === 'relation') {
        if (card?.kind === 'major') {
            return RELATION_MAJOR_READINGS[card.number]?.[orientationId] || '';
        }
        if (card?.kind === 'minor') {
            return RELATION_MINOR_READINGS[card.suitId]?.[card.rankId]?.[orientationId] || '';
        }
    }
    if (topicId === 'future') {
        if (card?.kind === 'major') {
            return FUTURE_MAJOR_READINGS[card.number]?.[orientationId] || '';
        }
        if (card?.kind === 'minor') {
            return FUTURE_MINOR_READINGS[card.suitId]?.[card.rankId]?.[orientationId] || '';
        }
    }
    return '';
}

