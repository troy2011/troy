function buildAbilitiesForAffinity(affinity, definition) {
    const expectedCounts = {
        manipulation: 55,
        specialization: 78,
        transmutation: 78,
        conjuration: 66,
        enhancement: 44,
        emission: 44
    };
    if (definition.abilities.length !== expectedCounts[affinity]) {
        throw new Error(`${affinity} count mismatch: expected ${expectedCounts[affinity]}, got ${definition.abilities.length}`);
    }
    const compatibleTypes = AFFINITY_TYPES[affinity];
    return definition.abilities.map(([name, effect], index) => {
        const profile = SPECIAL_ABILITY_PROFILES[name];
        if (!profile) throw new Error(`Missing authored profile for ${name}`);
        if (profile.affinity !== affinity) {
            throw new Error(`Profile affinity mismatch for ${name}: expected ${affinity}, got ${profile.affinity}`);
        }
        if (!compatibleTypes.includes(profile.targetType)) {
            throw new Error(`Profile target type mismatch for ${name}: ${profile.targetType}`);
        }
        return {
            id: `special-${affinity}-${String(index + 1).padStart(3, '0')}`,
            name,
            alias: profile.alias,
            effect,
            rule: profile.rule,
            affinity,
            affinityLabel: definition.label,
            compatibleTypes,
            targetType: profile.targetType,
            traitVector: vectorForType(profile.targetType),
            tempoTarget: profile.tempoTarget
        };
    });
}

const abilities = Object.entries(CURATED_ABILITIES)
    .flatMap(([affinity, definition]) => buildAbilitiesForAffinity(affinity, definition));
const abilityNames = new Set(abilities.map((ability) => ability.name));
const unusedProfiles = Object.keys(SPECIAL_ABILITY_PROFILES).filter((name) => !abilityNames.has(name));
if (unusedProfiles.length) throw new Error(`Unused authored profiles: ${unusedProfiles.join(', ')}`);
if (abilityNames.size !== Object.keys(SPECIAL_ABILITY_PROFILES).length) {
    throw new Error('Ability/profile coverage mismatch');
}

