function buildProfileMap(groups) {
    const profiles = {};
    Object.entries(groups).forEach(([affinity, entries]) => {
        entries.forEach(([name, rule, targetType, tempoTarget]) => {
            if (profiles[name]) throw new Error(`Duplicate special ability profile: ${name}`);
            const alias = SPECIAL_ABILITY_ALIASES[name];
            if (!alias) throw new Error(`Missing special ability alias: ${name}`);
            profiles[name] = Object.freeze({ affinity, alias, rule, targetType, tempoTarget });
        });
    });
    return Object.freeze(profiles);
}

module.exports = {
    PROFILE_GROUPS,
    SPECIAL_ABILITY_PROFILES: buildProfileMap(PROFILE_GROUPS)
};
