function parseJsonSafe(raw) {
    if (!raw) return null;
    try {
        const parsed = JSON.parse(raw);
        return parsed && typeof parsed === 'object' ? parsed : null;
    } catch {
        return null;
    }
}

function getJstDayKey() {
    const now = Date.now();
    const jst = new Date(now + 9 * 60 * 60 * 1000);
    return jst.toISOString().slice(0, 10);
}

function buildTarotDeck() {
    const deck = [];
    for (const suit of SUITS) {
        for (let number = 1; number <= 14; number += 1) {
            deck.push({
                id: `minor-${suit.toLowerCase()}-${number}`,
                number,
                suit,
                isArcana: false,
                effectType: 'None'
            });
        }
    }
    for (let number = 0; number <= 21; number += 1) {
        let suit = 'None';
        if (number === 1) suit = 'All';
        let effectType = 'None';
        if (number === 21) effectType = 'World';
        if (number === 20) effectType = 'Judgment';
        if (number === 0) effectType = 'Fool';
        deck.push({
            id: `arcana-${number}`,
            number,
            suit,
            isArcana: true,
            effectType
        });
    }
    return deck;
}

function pickRandom(list) {
    if (!Array.isArray(list) || !list.length) return null;
    const idx = Math.floor(Math.random() * list.length);
    return list[idx] || null;
}


function buildFortuneReward(card, orientation, ownedFragmentCount = 0) {
    const rewardItemName = getCardName(card);
    const rewardPs = getFortuneGoldRewardAmount(card);
    const goldLabel = rewardPs > 0 ? ` / +${rewardPs}G` : '';
    const rewardItemId = String(card?.id || '').trim();
    const isReversed = orientation === 'reversed';
    const currentFragmentCount = Math.max(0, Math.min(
        FORTUNE_FRAGMENT_REQUIREMENT - 1,
        Math.floor(Number(ownedFragmentCount) || 0)
    ));
    const rewardFragmentCount = isReversed ? currentFragmentCount + 1 : currentFragmentCount;
    const rewardFragmentCompleted = isReversed && rewardFragmentCount >= FORTUNE_FRAGMENT_REQUIREMENT;
    const rewardCardGranted = !isReversed || rewardFragmentCompleted;
    const rewardType = rewardCardGranted ? 'card' : 'fragment';
    const rewardLabel = rewardFragmentCompleted
        ? `${rewardItemName}の欠片がそろい、カードを獲得${goldLabel}`
        : (isReversed
            ? `${rewardItemName}の欠片を獲得（${rewardFragmentCount}/${FORTUNE_FRAGMENT_REQUIREMENT}）${goldLabel}`
            : `${rewardItemName}を1枚獲得${goldLabel}`);
    return {
        rewardType,
        rewardPs,
        rewardItemId,
        rewardItemName,
        rewardItemAmount: rewardCardGranted ? 1 : 0,
        rewardCardGranted,
        rewardFragmentAmount: isReversed ? 1 : 0,
        rewardFragmentCount: rewardFragmentCompleted ? 0 : rewardFragmentCount,
        rewardFragmentRequired: FORTUNE_FRAGMENT_REQUIREMENT,
        rewardFragmentCompleted,
        rewardLabel
    };
}

function getFortuneGoldRewardAmount(card) {
    const amount = Math.floor(Number(card?.number) || 0);
    return Math.max(0, amount);
}

function getCardName(card) {
    if (!card) return '';
    if (card.isArcana) {
        return ARCANA_NAME[Number(card.number)] || `大アルカナ${Number(card.number) || 0}`;
    }
    const suitLabel = SUIT_LABEL[String(card.suit)] || String(card.suit || '');
    const rankLabel = MINOR_RANK_LABEL[Number(card.number)] || String(card.number || '');
    return `${suitLabel}${rankLabel}`;
}

function formatFortuneText(text) {
    const value = String(text || '').trim();
    if (!value) return value;
    const lines = value.split(/\n+/)
        .flatMap((section) => section
            .match(/[^。！？!?]+[。！？!?]?/g)
            ?.map((line) => line.trim())
            .filter(Boolean) || [section.trim()])
        .filter(Boolean);
    return lines.join('\n');
}

function normalizeFortuneWeatherLevel(level) {
    const value = Math.floor(Number(level) || 0);
    if (value < 1) return 5;
    if (value > 10) return 10;
    return value;
}

function getFortuneWeather(card, orientation) {
    const dir = orientation === 'reversed' ? 'reversed' : 'upright';
    let level = 5;
    if (card?.isArcana) {
        level = FORTUNE_MAJOR_WEATHER_LEVELS[Number(card.number)]?.[dir] || 5;
    } else {
        const suitKey = String(card?.suit || 'Wand').toLowerCase();
        const rank = Number(card?.number) || 1;
        const exceptionLevel = FORTUNE_MINOR_WEATHER_EXCEPTIONS[`${suitKey}-${rank}`]?.[dir];
        level = exceptionLevel || FORTUNE_MINOR_WEATHER_LEVELS[dir]?.[rank] || 5;
    }
    const normalizedLevel = normalizeFortuneWeatherLevel(level);
    const status = FORTUNE_WEATHER_STATUSES[normalizedLevel] || FORTUNE_WEATHER_STATUSES[5];
    return {
        level: normalizedLevel,
        windLabel: status.windLabel,
        verdict: status.verdict
    };
}

function getFortuneStrikeLine(text) {
    const lines = formatFortuneText(text)
        .split(/\n+/)
        .map((line) => line.trim())
        .filter(Boolean);
    if (lines.length === 0) {
        return '今日は足元を整え、次の波に備えな。';
    }
    const meaningfulLine = [...lines].reverse().find((line) => {
        const compact = line.replace(/[\s。、！？!?「」『』（）()…・]/g, '');
        return compact.length >= 14;
    });
    return meaningfulLine || lines[lines.length - 1];
}

function buildFortuneReadingText(card, orientation, bodyText) {
    const weather = getFortuneWeather(card, orientation);
    const strikeLine = String(bodyText || '').replace(/\s*\n+\s*/g, ' ').trim()
        || '今日は足元を整え、次の波に備えな。';
    return [
        `風向き: ${weather.windLabel}`,
        '',
        strikeLine
    ].join('\n').replace(/\n{3,}/g, '\n\n').trim();
}

function formatMinorFortuneText(suit, dir, text) {
    const battleLine = MINOR_SUIT_BATTLE_LINE[suit]?.[dir] || '';
    return formatFortuneText([battleLine, text].filter(Boolean).join('\n'));
}

function getFortuneStrikeText(card, orientation) {
    const dir = orientation === 'reversed' ? 'reversed' : 'upright';
    if (card?.isArcana) {
        const dedicatedLine = MAJOR_DAILY_STRIKE_LINES[Number(card.number)]?.[dir];
        if (dedicatedLine) return dedicatedLine;
        const major = MAJOR_FORTUNE[Number(card.number)];
        const bodyText = major && major[dir]
            ? major[dir]
            : (dir === 'upright'
                ? '流れは悪くありません。ただし油断は穴になります。足元から整えてください。'
                : '焦りが潮を乱します。確認を一つ増やし、壊れる前に直してください。');
        return getFortuneStrikeLine(bodyText);
    }
    const suit = String(card?.suit || 'Wand');
    const rank = Number(card?.number) || 1;
    const dedicatedLine = MINOR_DAILY_STRIKE_LINES[suit]?.[rank]?.[dir];
    if (dedicatedLine) return dedicatedLine;
    const minor = MINOR_FORTUNE[suit]?.[rank]?.daily;
    const bodyText = minor && minor[dir]
        ? formatMinorFortuneText(suit, dir, minor[dir])
        : formatMinorFortuneText(suit, dir, dir === 'upright'
        ? '基本が一番残酷に差を出します。小さい作業を丁寧に終えてください。'
        : '無理に進めるほど傷が広がります。止める作業を一つ選んでください。');
    return getFortuneStrikeLine(bodyText);
}

function getFortuneText(card, orientation) {
    return buildFortuneReadingText(card, orientation, getFortuneStrikeText(card, orientation));
}

async function readFortuneRecord(playFabId, promisifyPlayFab, PlayFabServer) {
    const ro = await promisifyPlayFab(PlayFabServer.GetUserReadOnlyData, {
        PlayFabId: playFabId,
        Keys: [FORTUNE_DATA_KEY]
    });
    const raw = ro?.Data?.[FORTUNE_DATA_KEY]?.Value || '';
    return parseJsonSafe(raw);
}

